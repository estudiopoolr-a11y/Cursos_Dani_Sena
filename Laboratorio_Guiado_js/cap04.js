//Operadores aritmeticos 
let a = 10;
let b = 5;

console.log(a + b);

//Resta,mulriplicacion,division y modulo
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);

//invremento y decremento
a++;
console.log(a); // esto significa que a = a + 1, por lo que el valor de a ahora es 11

b--;
console.log(b); // esto significa que b = b - 1, por lo que el valor de b ahora es 4