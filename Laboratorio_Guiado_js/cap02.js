/* Variables con let */
let nombre = "Dani";
console.log(nombre); 
/*
Modificando variables
*/
let edad = 30;
console.log(edad);
edad = 31;
console.log(edad);
/* Variables con const */
const PI = 3.14159;
console.log(PI);
/* Las variables declaradas con const no pueden ser reasignadas. */
